// Service worker entry: MSW's generated worker plus one fix.
//
// Opening DevTools makes Chrome re-request the current page with
// cache: 'only-if-cached'. MSW passes same-origin ones through to fetch(),
// which rejects when the page is not in the HTTP cache (any URL reached by
// client-side navigation) and logs "Uncaught (in promise) TypeError: Failed
// to fetch". Stop such requests before MSW's listener sees them; the browser
// then answers them from its cache on its own.
self.addEventListener('fetch', (event) => {
  if (event.request.cache === 'only-if-cached') event.stopImmediatePropagation()
})

